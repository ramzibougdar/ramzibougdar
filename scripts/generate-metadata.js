#!/usr/bin/env node
/* ==========================================================================
   generate-metadata.js — CV Ramzi Bougdar (maintenance tool, not a build step)
   Derives from data/cv.js everything that must be readable without JavaScript:
   - the pre-rendered CV inside the [data-render] containers of en/ and fr/ (rendered by the
     real js/main.js in headless Chrome, ?prerender mode), so every robot reads the whole CV;
   - the <head> links and social cards (canonical, hreflang, Open Graph) of each page;
   - the schema.org JSON-LD (ProfilePage about a Person) of each page;
   - sitemap.xml, and the llms.txt files: /llms.txt (English) and /fr/llms.txt (French).
   Usage:
   - node scripts/generate-metadata.js           checks every file, exits with 1 on any gap
   - node scripts/generate-metadata.js --write   rewrites every file
   Headless Chrome is needed for the pre-render (CHROME=/path/to/chrome to override).
   Email and phone are left out on purpose: they stay hidden from robots.
   ========================================================================== */

'use strict';

var fs = require('fs');
var path = require('path');
var vm = require('vm');
var childProcess = require('child_process');

var ROOT = path.join(__dirname, '..');
var LANGUAGES = ['en', 'fr'];
var CHROME = process.env.CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';

/** Marks the generated JSON-LD block in each page. */
var LD_START = '  <!-- Structured data (schema.org JSON-LD), generated from data/cv.js by scripts/generate-metadata.js -->\n';
var LD_BLOCK = /  <!-- Structured data \(schema\.org JSON-LD\)[^\n]*\n  <script type="application\/ld\+json">[\s\S]*?<\/script>\n/;

/** Marks the generated <head> links and social cards. */
var HEAD_START = '  <!-- Canonical, language alternates and social cards, generated by scripts/generate-metadata.js -->\n';
var HEAD_END = '  <!-- /generated links -->\n';
var HEAD_BLOCK = /  <!-- Canonical, language alternates and social cards[^\n]*\n[\s\S]*?  <!-- \/generated links -->\n/;

/** Marks the pre-rendered content inside a container. */
var PRE_START = '<!-- prerendered -->';
var PRE_END = '<!-- /prerendered -->';

/** Wording of the llms.txt files, per language. */
var LABELS = {
  en: {
    locale: 'en-GB', ogLocale: 'en_GB', present: 'present', colon: ': ',
    location: 'Location', current: 'Current position', since: 'since', at: 'at',
    experience: 'Professional experience', assignments: 'Client assignments', education: 'Education',
    skills: 'Skills', languages: 'Languages', internship: 'internship', highlights: 'Key results',
    pages: 'CV', page: 'Online CV (English)', otherPage: 'Online CV in French', pdf: 'PDF CV (English)',
    profiles: 'Profiles', otherLlms: 'llms.txt in French',
    contact: 'To contact Ramzi Bougdar, use the Contact section of the online CV.'
  },
  fr: {
    locale: 'fr-FR', ogLocale: 'fr_FR', present: 'aujourd\'hui', colon: ' : ',
    location: 'Localisation', current: 'Poste actuel', since: 'depuis', at: 'chez',
    experience: 'Expérience professionnelle', assignments: 'Missions chez des clients', education: 'Formation',
    skills: 'Compétences', languages: 'Langues', internship: 'stage', highlights: 'Résultats clés',
    pages: 'CV', page: 'CV en ligne (français)', otherPage: 'CV en ligne en anglais', pdf: 'CV en PDF (français)',
    profiles: 'Profils', otherLlms: 'llms.txt en anglais',
    contact: 'Pour contacter Ramzi Bougdar, utilisez la section Contact du CV en ligne.'
  }
};

/* --------------------------------------------------------------------------
   Data helpers
   -------------------------------------------------------------------------- */

/**
 * Loads window.CV_DATA from data/cv.js without a browser.
 * @returns {Object}
 */
function loadCV() {
  var sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'data/cv.js'), 'utf8'), sandbox);
  return sandbox.window.CV_DATA;
}

/**
 * Tells whether a value is a bilingual text { "en": …, "fr": … }.
 * @param {*} value
 * @returns {boolean}
 */
function isBilingual(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return false;
  var keys = Object.keys(value);
  return keys.length > 0 && keys.every(function (k) { return LANGUAGES.indexOf(k) !== -1; });
}

/**
 * Copy of the data in one language (same rule as js/i18n.js: English as fallback).
 * @param {*} value
 * @param {string} lang
 * @returns {*}
 */
function localize(value, lang) {
  if (isBilingual(value)) return localize(value[lang] !== undefined ? value[lang] : value.en, lang);
  if (Array.isArray(value)) return value.map(function (v) { return localize(v, lang); });
  if (value && typeof value === 'object') {
    var copy = {};
    Object.keys(value).forEach(function (k) { copy[k] = localize(value[k], lang); });
    return copy;
  }
  return value;
}

/**
 * Keeps only the defined, non-empty values of an object.
 * @param {Object} obj
 * @returns {Object}
 */
function clean(obj) {
  Object.keys(obj).forEach(function (k) {
    var v = obj[k];
    if (v === null || v === undefined || v === '' || (Array.isArray(v) && !v.length)) delete obj[k];
  });
  return obj;
}

/**
 * Strings of a list ("to be clarified" items are skipped).
 * @param {Array} list
 * @returns {string[]}
 */
function strings(list) {
  return (list || []).filter(function (v) { return typeof v === 'string'; });
}

/**
 * Employer with an ongoing position (end: null).
 * @param {Object} cv localized data
 * @returns {Object|undefined}
 */
function currentEmployer(cv) {
  return (cv.experiences || []).filter(function (e) {
    return (e.positions || []).some(function (p) { return !p.end; });
  })[0];
}

/**
 * Site root URL with a trailing slash (meta.siteUrl of data/cv.js).
 * @param {Object} data
 * @returns {string}
 */
function siteUrl(data) {
  var url = (data.meta && data.meta.siteUrl) || '';
  if (!/^https:\/\//.test(url)) throw new Error('meta.siteUrl must be an https:// URL in data/cv.js');
  return url.replace(/\/?$/, '/');
}

/**
 * Escapes a text for an HTML attribute value.
 * @param {string} text
 * @returns {string}
 */
function attr(text) {
  return String(text).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

/**
 * Decodes the few entities used in <title> and meta description.
 * @param {string} text
 * @returns {string}
 */
function decode(text) {
  return String(text).replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
}

/* --------------------------------------------------------------------------
   Pre-render (headless Chrome runs the real js/main.js)
   -------------------------------------------------------------------------- */

/**
 * Renders a language page in headless Chrome (?final&prerender) and returns the HTML of
 * each [data-render] container, as exported by main.js.
 * @param {string} lang
 * @returns {Object<string, string>}
 */
function prerender(lang) {
  if (!fs.existsSync(CHROME)) throw new Error('Headless Chrome not found at ' + CHROME + ' (set CHROME=…)');
  var url = 'file://' + path.join(ROOT, lang, 'index.html') + '?final&prerender';
  var dom = childProcess.execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--allow-file-access-from-files',
    '--virtual-time-budget=8000', '--dump-dom', url], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 1 << 26 });
  var found = /<script type="application\/json" id="prerender-output">([\s\S]*?)<\/script>/.exec(dom);
  if (!found) throw new Error('No pre-render output for ' + lang + '/ (did main.js fail?)');
  return JSON.parse(found[1]);
}

/**
 * Writes the pre-rendered content into the [data-render] containers of a page source.
 * @param {string} html page source
 * @param {Object<string, string>} parts container name → inner HTML
 * @returns {string}
 */
function withPrerender(html, parts) {
  Object.keys(parts).forEach(function (name) {
    var content = PRE_START + parts[name] + PRE_END;
    var marked = new RegExp('(data-render="' + name + '"[^>]*>)' + PRE_START + '[\\s\\S]*?' + PRE_END);
    if (marked.test(html)) {
      html = html.replace(marked, function (m, open) { return open + content; });
      return;
    }
    // First run: the container is still empty or holds plain fallback text.
    var empty = new RegExp('(<(\\w+)[^>]*\\bdata-render="' + name + '"[^>]*>)([^<]*)(</\\2>)');
    if (!empty.test(html)) throw new Error('Container data-render="' + name + '" not found or not empty');
    html = html.replace(empty, function (m, open, tag, text, close) { return open + content + close; });
  });
  return html;
}

/* --------------------------------------------------------------------------
   <head> links, social cards and JSON-LD
   -------------------------------------------------------------------------- */

/**
 * Canonical, hreflang alternates and Open Graph / Twitter tags of a language page.
 * Title and description are read from the page itself.
 * @param {Object} data
 * @param {string} lang
 * @param {string} html page source
 * @returns {string}
 */
function headBlock(data, lang, html) {
  var site = siteUrl(data);
  var cv = localize(data, lang);
  var L = LABELS[lang];
  var other = lang === 'en' ? 'fr' : 'en';
  var title = decode((/<title>([^<]*)<\/title>/.exec(html) || [])[1] || '');
  var description = decode((/<meta name="description" content="([^"]*)">/.exec(html) || [])[1] || '');
  var photo = cv.profile && cv.profile.photo;
  var lines = [
    '<link rel="canonical" href="' + site + lang + '/">',
    '<link rel="alternate" hreflang="en" href="' + site + 'en/">',
    '<link rel="alternate" hreflang="fr" href="' + site + 'fr/">',
    '<link rel="alternate" hreflang="x-default" href="' + site + '">',
    '<meta property="og:type" content="profile">',
    '<meta property="og:site_name" content="' + attr(cv.profile.name) + '">',
    '<meta property="og:title" content="' + attr(title) + '">',
    '<meta property="og:description" content="' + attr(description) + '">',
    '<meta property="og:url" content="' + site + lang + '/">',
    '<meta property="og:locale" content="' + L.ogLocale + '">',
    '<meta property="og:locale:alternate" content="' + LABELS[other].ogLocale + '">'
  ];
  if (photo && photo.src) {
    lines.push('<meta property="og:image" content="' + site + photo.src + '">');
    if (photo.width) lines.push('<meta property="og:image:width" content="' + photo.width + '">');
    if (photo.height) lines.push('<meta property="og:image:height" content="' + photo.height + '">');
    if (typeof photo.alt === 'string') lines.push('<meta property="og:image:alt" content="' + attr(photo.alt) + '">');
  }
  lines.push('<meta name="twitter:card" content="summary">');
  return HEAD_START + lines.map(function (l) { return '  ' + l + '\n'; }).join('') + HEAD_END;
}

/**
 * Language alternates of the root page (it only routes visitors to a language).
 * @param {Object} data
 * @returns {string}
 */
function rootHeadBlock(data) {
  var site = siteUrl(data);
  return HEAD_START + [
    '<link rel="canonical" href="' + site + '">',
    '<link rel="alternate" hreflang="en" href="' + site + 'en/">',
    '<link rel="alternate" hreflang="fr" href="' + site + 'fr/">',
    '<link rel="alternate" hreflang="x-default" href="' + site + '">'
  ].map(function (l) { return '  ' + l + '\n'; }).join('') + HEAD_END;
}

/**
 * Inserts or replaces the <head> block, right after the color-scheme meta.
 * @param {string} html
 * @param {string} block
 * @returns {string}
 */
function withHead(html, block) {
  if (HEAD_BLOCK.test(html)) return html.replace(HEAD_BLOCK, function () { return block; });
  var anchor = /  <meta name="color-scheme"[^>]*>\n/;
  if (!anchor.test(html)) throw new Error('color-scheme meta not found');
  return html.replace(anchor, function (m) { return m + block; });
}

/**
 * Builds the JSON-LD object of one language page.
 * @param {Object} data bilingual CV data
 * @param {string} lang
 * @returns {Object}
 */
function structuredData(data, lang) {
  var site = siteUrl(data);
  var cv = localize(data, lang);
  var profile = cv.profile || {};
  var contact = cv.contact || {};
  var place = typeof profile.location === 'string' ? profile.location.split(',').map(function (p) { return p.trim(); }) : [];
  var current = currentEmployer(cv);
  var isUrl = function (u) { return typeof u === 'string' && /^https:\/\//.test(u); };

  return clean({
    '@context': 'https://schema.org',
    '@type': 'ProfilePage',
    '@id': site + lang + '/',
    url: site + lang + '/',
    inLanguage: lang,
    dateModified: cv.meta && cv.meta.updatedOn,
    mainEntity: clean({
      '@type': 'Person',
      '@id': site + '#person',
      name: profile.name,
      url: site,
      jobTitle: typeof profile.title === 'string' ? profile.title : null,
      description: strings(profile.summary)[0] || null,
      image: profile.photo && profile.photo.src ? site + profile.photo.src : null,
      address: place.length ? clean({
        '@type': 'PostalAddress', addressLocality: place[0], addressRegion: place[1], addressCountry: place[place.length - 1]
      }) : null,
      worksFor: current ? { '@type': 'Organization', name: current.employer } : null,
      alumniOf: (cv.education || []).filter(function (e) { return typeof e.school === 'string'; })
        .map(function (e) { return { '@type': 'EducationalOrganization', name: e.school }; }),
      knowsAbout: [].concat.apply([], (cv.skills || []).map(function (g) { return strings(g.items); })),
      knowsLanguage: strings((cv.languages || []).map(function (l) { return l.language; })),
      sameAs: [contact.linkedin, contact.github, contact.instagram, contact.tiktok].filter(isUrl)
    })
  });
}

/**
 * HTML block of a JSON-LD object; "<" is escaped so the text can never close the script tag.
 * @param {Object} obj
 * @returns {string}
 */
function jsonLdBlock(obj) {
  var json = JSON.stringify(obj, null, 2).replace(/</g, '\\u003c').replace(/\n/g, '\n  ');
  return LD_START + '  <script type="application/ld+json">\n  ' + json + '\n  </script>\n';
}

/**
 * Inserts or replaces the JSON-LD block, right before </head>.
 * @param {string} html
 * @param {string} block
 * @returns {string}
 */
function withJsonLd(html, block) {
  return LD_BLOCK.test(html) ? html.replace(LD_BLOCK, function () { return block; }) : html.replace('</head>', block + '</head>');
}

/* --------------------------------------------------------------------------
   sitemap.xml and llms.txt
   -------------------------------------------------------------------------- */

/**
 * sitemap.xml listing both language pages with their alternates and last update.
 * @param {Object} data
 * @returns {string}
 */
function sitemap(data) {
  var site = siteUrl(data);
  var updated = data.meta && data.meta.updatedOn;
  var alternates = LANGUAGES.map(function (l) {
    return '    <xhtml:link rel="alternate" hreflang="' + l + '" href="' + site + l + '/"/>';
  }).concat('    <xhtml:link rel="alternate" hreflang="x-default" href="' + site + '"/>').join('\n');
  return '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<!-- Generated from data/cv.js by scripts/generate-metadata.js -->\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' +
    LANGUAGES.map(function (l) {
      return '  <url>\n    <loc>' + site + l + '/</loc>\n' + (updated ? '    <lastmod>' + updated + '</lastmod>\n' : '') + alternates + '\n  </url>';
    }).join('\n') + '\n</urlset>\n';
}

/**
 * Builds the llms.txt of one language (https://llmstxt.org): title, summary, key facts,
 * then link sections with absolute URLs.
 * @param {Object} data bilingual CV data
 * @param {string} lang
 * @returns {string}
 */
function llmsTxt(data, lang) {
  var site = siteUrl(data);
  var cv = localize(data, lang);
  var L = LABELS[lang];
  var other = lang === 'en' ? 'fr' : 'en';
  var profile = cv.profile || {};
  var contact = cv.contact || {};
  var monthFormat = new Intl.DateTimeFormat(L.locale, { month: 'long', year: 'numeric' });
  /** "YYYY-MM" → "February 2023"; "YYYY" stays as is; null → "present". */
  var date = function (v) {
    if (!v) return L.present;
    var m = /^(\d{4})-(\d{2})$/.exec(v);
    return m ? monthFormat.format(new Date(+m[1], +m[2] - 1, 1)) : String(v);
  };
  var out = [];

  out.push('# ' + profile.name, '');
  if (typeof profile.title === 'string') out.push('> ' + profile.title, '');
  strings(profile.summary).forEach(function (p) { out.push(p, ''); });

  // Key facts
  var facts = [];
  if (typeof profile.location === 'string') facts.push('- ' + L.location + L.colon + profile.location);
  var current = currentEmployer(cv);
  if (current) {
    var position = current.positions.filter(function (p) { return !p.end; })[0];
    facts.push('- ' + L.current + L.colon + position.title + ' ' + L.at + ' ' + current.employer + ' (' + L.since + ' ' + date(position.start) + ')');
  }
  if (facts.length) out.push(facts.join('\n'), '');

  // Experience, then client assignments (positions of type "mission")
  var jobs = [], assignments = [];
  (cv.experiences || []).forEach(function (e) {
    (e.positions || []).forEach(function (p) {
      var line = '- ' + e.employer + ' — ' + p.title + (p.type === 'internship' ? ' (' + L.internship + ')' : '') +
        ', ' + date(p.start) + ' – ' + date(p.end) + (typeof p.description === 'string' ? L.colon + p.description : '');
      var details = strings(p.highlights).map(function (h) { return '  - ' + L.highlights + L.colon + h; })
        .concat(strings(p.missions).map(function (m) { return '  - ' + m; }));
      (p.type === 'mission' ? assignments : jobs).push([line].concat(details).join('\n'));
    });
  });
  if (jobs.length) out.push('**' + L.experience + '**', '', jobs.join('\n'), '');
  if (assignments.length) out.push('**' + L.assignments + '**', '', assignments.join('\n'), '');

  var schools = (cv.education || []).map(function (e) {
    return '- ' + e.school + ' — ' + [e.degree, e.field].filter(function (v) { return typeof v === 'string'; }).join(', ') + ' (' + e.start + '–' + e.end + ')';
  });
  if (schools.length) out.push('**' + L.education + '**', '', schools.join('\n'), '');

  var skills = (cv.skills || []).map(function (g) { return '- ' + g.category + L.colon + strings(g.items).join(', '); });
  if (skills.length) out.push('**' + L.skills + '**', '', skills.join('\n'), '');

  var languages = (cv.languages || []).map(function (l) { return '- ' + l.language + L.colon + l.level; });
  if (languages.length) out.push('**' + L.languages + '**', '', languages.join('\n'), '');

  out.push(L.contact, '');

  // Link sections ("Optional" is the reserved name of the llms.txt format)
  out.push('## ' + L.pages, '');
  out.push('- [' + L.page + '](' + site + lang + '/)');
  if (cv.pdf && typeof cv.pdf.file === 'string') out.push('- [' + L.pdf + '](' + site + cv.pdf.file + ')');
  out.push('');
  var networks = [['LinkedIn', contact.linkedin], ['GitHub', contact.github], ['Instagram', contact.instagram], ['TikTok', contact.tiktok]]
    .filter(function (n) { return typeof n[1] === 'string' && /^https:\/\//.test(n[1]); });
  if (networks.length) {
    out.push('## ' + L.profiles, '');
    networks.forEach(function (n) { out.push('- [' + n[0] + '](' + n[1] + ')'); });
    out.push('');
  }
  out.push('## Optional', '');
  out.push('- [' + L.otherPage + '](' + site + other + '/)');
  out.push('- [' + L.otherLlms + '](' + site + (other === 'en' ? 'llms.txt' : other + '/llms.txt') + ')');
  return out.join('\n') + '\n';
}

/* --------------------------------------------------------------------------
   Check / write
   -------------------------------------------------------------------------- */

/** Checks (or rewrites with --write) every generated file. */
function main() {
  var write = process.argv.indexOf('--write') !== -1;
  var data = loadCV();
  var targets = [];

  LANGUAGES.forEach(function (lang) {
    var page = path.join(ROOT, lang, 'index.html');
    var html = fs.readFileSync(page, 'utf8');
    var expected = withPrerender(html, prerender(lang));
    expected = withHead(expected, headBlock(data, lang, expected));
    expected = withJsonLd(expected, jsonLdBlock(structuredData(data, lang)));
    targets.push({ file: page, expected: expected });
  });
  var rootPage = path.join(ROOT, 'index.html');
  targets.push({ file: rootPage, expected: withHead(fs.readFileSync(rootPage, 'utf8'), rootHeadBlock(data)) });
  targets.push({ file: path.join(ROOT, 'sitemap.xml'), expected: sitemap(data) });
  targets.push({ file: path.join(ROOT, 'llms.txt'), expected: llmsTxt(data, 'en') });
  targets.push({ file: path.join(ROOT, 'fr', 'llms.txt'), expected: llmsTxt(data, 'fr') });

  var gaps = 0;
  targets.forEach(function (t) {
    var name = path.relative(ROOT, t.file);
    var current = fs.existsSync(t.file) ? fs.readFileSync(t.file, 'utf8') : null;
    if (current === t.expected) { console.log(name + ': up to date'); return; }
    if (write) {
      fs.writeFileSync(t.file, t.expected);
      console.log(name + ': ' + (current === null ? 'created' : 'updated'));
    } else {
      gaps++;
      console.error(name + ': ' + (current === null ? 'missing' : 'out of date') + ' — run: node scripts/generate-metadata.js --write');
    }
  });
  if (gaps) process.exit(1);
}

main();
